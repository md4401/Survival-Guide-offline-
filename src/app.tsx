import { Learn, Quiz, Trees, KnowledgeMap, Drill } from './features/learn/Learn';
import { t } from './i18n';

export function App() {
  useSettings();
  const [r, arg, arg2] = usePath();
  let view;
  switch (r) {
    case undefined: view = <Home />; break;
    case 'triage': view = arg ? <TriageResult id={arg} /> : <Triage />; break;
    case 'emergency': view = <Emergency />; break;
    case 'numbers': view = <Numbers />; break;
    case 'torch': view = <Torch />; break;
    case 'whistle': view = <Whistle />; break;
    case 'messages': view = arg === 'sync' ? <Sync /> : arg === 'c' ? <Thread id={arg2 ?? 'public'} /> : <MessagesHub />; break;
    case 'signal': view = <Signal />; break;
    case 'trail': view = <Trail />; break;
    case 'medcard': view = <MedCard />; break;
    case 'silent': view = <Silent />; break;
    case 'inventory': view = <Inventory />; break;
    case 'compass': view = <Compass />; break;
    case 'gps': view = <Gps />; break;
    case 'search': view = <Search />; break;
    case 'plans': view = <Plans />; break;
    case 'legal': view = <Legal doc={arg === 'terms' ? 'terms' : 'privacy'} />; break;
    case 'about': view = <About />; break;
    case 'system': view = <System />; break;
    case 'settings': view = <Settings />; break;
    case 'guide': view = <GuideView id={arg ?? ''} />; break;
    case 'scenarios': view = <ListPage kind="scenario" titleKey="list.scenarios" />; break;
    case 'guides': view = <ListPage kind="guide" titleKey="list.guides" />; break;
    case 'prepare': view = arg === 'kit' ? <Kit kit={arg2 ?? '72h'} /> : arg === 'family' ? <Family /> : arg === 'water' ? <Water /> : arg === 'stock' ? <Stock /> : arg === 'energy' ? <Energy /> : arg === 'docs' ? <Documents /> : arg === 'plan72' ? <Plan72 /> : arg === 'score' ? <Readiness /> : <Prepare />; break;
    case 'tools': view = arg === 'converter' ? <Converter /> : arg === 'distance' ? <Distance /> : arg === 'level' ? <Level /> : arg === 'morse' ? <Morse /> : arg === 'notes' ? <Notes /> : arg === 'calculator' ? <Calculator /> : arg === 'recorder' ? <Recorder /> : arg === 'qrscan' ? <QrScan /> : arg === 'agenda' ? <Agenda /> : arg === 'decibel' ? <Decibel /> : arg === 'metal' ? <MetalDetector /> : arg === 'timer' ? <Timer /> : <ToolsHub />; break;
    case 'assistant': view = arg === 'models' ? <Models /> : <Assistant />; break;
    case 'learn': view = arg === 'quiz' ? <Quiz /> : arg === 'trees' ? <Trees id={arg2} /> : arg === 'map' ? <KnowledgeMap /> : arg === 'drill' ? <Drill /> : <Learn />; break;
    case 'library': { const V: Record<string, any> = { myths: Myths, facts: Facts, cases: Cases, diy: Diy, glossary: Glossary, phrases: Phrases, find: Find, scales: Scales }; const C = arg ? V[arg] : Library; view = C ? <C /> : <Library />; break; }
    case 'crisis': view = <Crisis />; break;
    case 'onboarding': view = <Onboarding />; break;
    case 'world': {
      const W: Record<string, any> = { clock: Clock, counter: Counter, sun: SunMoon, calendar: CalendarPage, countries: Countries, climate: Climate, tables: Tables, zones: ClimateZones, cmap: ClimateMap, numbers: WorldNumbers };
      const V = arg ? W[arg] : World;
      view = V ? <V /> : <World />; break;
    }
    default: view = <main><p>{t('guide.notFound')}</p></main>;
  }
  return <Layout route={r ?? ''}>{view}</Layout>;
}
